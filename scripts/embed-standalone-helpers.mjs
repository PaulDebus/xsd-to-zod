#!/usr/bin/env node
// Embeds the helper modules that standalone codegen inlines into a generated
// TypeScript constant, so irToZod never needs filesystem access. Rerun after
// editing any of the helper sources; tests assert the result is current.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MODULES = [
  "xsdLexicals.ts",
  "xsdDateTime.ts",
  "xsdChecks.ts",
  "xsdPattern.ts",
  "choiceCheck.ts",
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entries = MODULES.map((file) => {
  const source = readFileSync(path.join(root, "src", file), "utf8");
  return `  ${JSON.stringify(file)}: ${JSON.stringify(source)},`;
});
const output = `// AUTO-GENERATED by scripts/embed-standalone-helpers.mjs — DO NOT EDIT.
// Run \`npm run gen:standalone\` after changing any inlined helper source.
export const STANDALONE_HELPER_SOURCES: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;
writeFileSync(path.join(root, "src", "standaloneHelperSources.generated.ts"), output);
